/**
 * Fractional line-item quantities, limited to 2 decimal places, and the order
 * form's New order action.
 *
 * Quantities can be fractional because the Decimal Product Quantity plugin is
 * active on both sites. Before 7.1 the app clamped every quantity to a whole
 * number and the plugin (int)-cast it on both the way in and the way out, so
 * 1.5 silently became 1 - a wrong order with no error. These assertions cover
 * the app's half: the rounding rule, the input, the payload, and the places
 * the old integer assumption could quietly survive.
 *
 * The rounding cases are pinned to values PRODUCED BY RUNNING the plugin's
 * ai_rest_line_quantity() under PHP 8.3 with a float-safe stock filter, the
 * same way phone-parity pins phone.js. If the PHP rule changes, regenerate
 * them rather than editing them to pass.
 *
 * Run with `npm test` from app/.
 */

